#!/usr/bin/env python3
"""Build one offline-capable Bash distribution from the modular sources."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
resources = {p.name: p.read_text(encoding='utf-8') for p in sorted((ROOT / 'src/sql').glob('*.sql'))}
resources['transformer.py'] = (ROOT / 'src/transformer.py').read_text(encoding='utf-8')
launcher = (ROOT / 'src/launcher.py').read_text(encoding='utf-8')
assert all('\"\"\"' not in text and text.endswith('\n') for text in resources.values())
resource_block = 'RESOURCES = {\n' + ''.join(
    repr(name) + ': r\"\"\"' + text + '\"\"\",\n' for name, text in resources.items()) + '}\n'
launcher = launcher.replace('RESOURCES = {}  # Injected into the distributable; never downloaded at runtime.',
                            resource_block)
header = '''#!/usr/bin/env bash
# flexmysqlbackup — https://github.com/tuthon/flexmysqlbackup
# SPDX-License-Identifier: GPL-2.0-only
# Generated by build.py. Requires Bash, Python 3.8+, MySQL client, GNU sed.
# mysqldump is needed only when backing up table data.
set -euo pipefail

# Connection defaults; the interactive menu asks once at startup.
export MYSQL_HOST="${MYSQL_HOST:-localhost}"
export MYSQL_PORT="${MYSQL_PORT:-3306}"
export MYSQL_USER="${MYSQL_USER:-devops}"

# Routine exclusions. JSON arrays; LIKE: % = any text, _ = one character.
export EXCLUDE_SP_PATTERNS_JSON="${EXCLUDE_SP_PATTERNS_JSON:-[\\"%copy\\",\\"%copy1\\",\\"%copy2\\",\\"%copy3\\",\\"alter_table\\",\\"%transfer_casino_balance_shard%\\"]}"
export EXCLUDED_SCHEMAS_JSON="${EXCLUDED_SCHEMAS_JSON:-[]}"
export MAX_DIGITS_IN_NAME="${MAX_DIGITS_IN_NAME:-5}"
# Migration settings, used only for transformed exports and --transform.
export QUOTE_IDENTIFIERS="${QUOTE_IDENTIFIERS:-over groups rank dense_rank row_number cume_dist percent_rank ntile lag lead first_value last_value nth_value recursive window lateral}"
export CONVERT_UTF8_TO_UTF8MB4="${CONVERT_UTF8_TO_UTF8MB4:-1}"
export REMOVE_GROUP_BY_DESC="${REMOVE_GROUP_BY_DESC:-1}"

command -v python3 >/dev/null || { echo 'python3 is required.' >&2; exit 1; }
# fd 3 carries Python code; stdin remains available for interactive input.
exec python3 /dev/fd/3 "$@" 3<<'FLEXMYSQLBACKUP_PYTHON'
'''
target = ROOT / 'flexmysqlbackup.sh'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if the generated distribution is stale')
args = parser.parse_args()
payload = header + launcher + '\nFLEXMYSQLBACKUP_PYTHON\n'
if args.check:
    if not target.is_file() or target.read_text(encoding='utf-8') != payload:
        parser.exit(1, 'flexmysqlbackup.sh is stale; run python3 build.py\n')
    print('flexmysqlbackup.sh matches its modular sources.')
else:
    target.write_text(payload, encoding='utf-8')
    target.chmod(0o755)
    print(target)
